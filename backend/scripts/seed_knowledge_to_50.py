def seed_to_50():
    check_inference_server()
    db = SessionLocal()
    inserted_count = 0
    vector_count = 0
    skipped_count = 0
    errors = []

    try:
        current_count = db.query(KnowledgeItem).count()
        target_count = 50
        if current_count >= target_count:
            logger.info(f"知识库当前已有 {current_count} 条，无需补充")
            return

        needed = target_count - current_count
        logger.info(f"当前知识库 {current_count} 条，计划新增 {needed} 条")

        for item in EXTRA_KNOWLEDGE:
            if inserted_count >= needed:
                break
            try:
                existing = db.query(KnowledgeItem).filter(
                    KnowledgeItem.title == item["title"]
                ).first()
                if existing:
                    skipped_count += 1
                    continue

                knowledge = KnowledgeItem(
                    title=item["title"],
                    content=item["content"],
                    device_type=item.get("device_type"),
                    fault_code=item.get("fault_code"),
                    fault_tags=item.get("fault_tags", []),
                    source_type="SEED",
                    status=KnowledgeStatus.PUBLISHED,
                    version=1,
                )
                db.add(knowledge)
                db.flush()

                text_for_embedding = f"{item['title']}\n{item['content'][:settings.MAX_VECTOR_CONTENT_LEN]}"
                vector = encode_text(text_for_embedding)
                point_id = vector_store.insert(
                    vector=vector,
                    knowledge_id=knowledge.id,
                    title=item["title"],
                    content=item["content"],
                    device_type=item.get("device_type"),
                    fault_code=item.get("fault_code"),
                    fault_tags=item.get("fault_tags", []),
                )
                knowledge.milvus_id = point_id
                db.flush()
                inserted_count += 1
                vector_count += 1
            except Exception as e:
                errors.append(f"'{item['title'][:30]}' 失败: {e}")
                logger.warning(f"  第 {inserted_count + 1} 条失败: {e}")
                db.rollback()

        db.commit()
        if vector_count > 0:
            vector_store.flush()
        logger.info(
            f"知识库补齐完成: 新增 {inserted_count} 条, 跳过 {skipped_count} 条, "
            f"失败 {len(errors)} 条"
        )
        if errors:
            logger.warning("失败清单:\n" + "\n".join(errors[:10]))
    finally:
        db.close()


if __name__ == "__main__":
    seed_to_50()
