# ==================== 导入逻辑 ====================

def seed_knowledge():
    """主导入函数"""
    check_inference_server()
    logger.info(f"开始导入 {len(SEED_KNOWLEDGE)} 条知识条目...")

    db = SessionLocal()
    inserted_count = 0
    vector_count = 0
    skipped_count = 0
    errors = []

    try:
        for i, item in enumerate(SEED_KNOWLEDGE):
            try:
                # 检查是否已存在相同标题
                existing = db.query(KnowledgeItem).filter(
                    KnowledgeItem.title == item["title"]
                ).first()
                if existing:
                    skipped_count += 1
                    continue

                # 1. 写入 PostgreSQL
                knowledge = KnowledgeItem(
                    title=item["title"],
                    content=item["content"],
                    device_type=item.get("device_type"),
                    fault_code=item.get("fault_code"),
                    fault_tags=item.get("fault_tags", []),
                    source_type="SEED",
                    status=KnowledgeStatus.PUBLISHED,
                    version=1,
                )
                db.add(knowledge)
                db.flush()  # 获得 knowledge.id

                # 2. 写入 Milvus 向量库
                text_for_embedding = f"{item['title']}\n{item['content'][:settings.MAX_VECTOR_CONTENT_LEN]}"
                vector = encode_text(text_for_embedding)

                point_id = vector_store.insert(
                    vector=vector,
                    knowledge_id=knowledge.id,
                    title=item["title"],
                    content=item["content"],
                    device_type=item.get("device_type"),
                    fault_code=item.get("fault_code"),
                    fault_tags=item.get("fault_tags", []),
                )

                # 更新 milvus_id 关联
                knowledge.milvus_id = point_id
                db.flush()
                inserted_count += 1
                vector_count += 1

                if (i + 1) % 20 == 0:
                    db.commit()
                    logger.info(f"  已处理: {i + 1}/{len(SEED_KNOWLEDGE)}")

            except Exception as e:
                errors.append(f"第 {i+1} 条 '{item['title'][:30]}' 失败: {e}")
                logger.warning(f"  第 {i+1} 条失败: {e}")
                db.rollback()

        # 最终提交
        db.commit()

        # 批量向量插入完成后统一 flush
        if vector_count > 0:
            vector_store.flush()
            logger.info("向量数据已刷写落盘")

        logger.info(f"导入完成: 成功 {inserted_count} 条, 跳过 {skipped_count} 条, 失败 {len(errors)} 条")
        logger.info(f"向量化: {vector_count} 条")

        if errors:
            logger.warning(f"失败清单:\n" + "\n".join(errors[:10]))
            if len(errors) > 10:
                logger.warning(f"  ... 共 {len(errors)} 条错误")

    except Exception as e:
        db.rollback()
        logger.error(f"导入过程异常终止: {e}")
        raise
    finally:
        db.close()


if __name__ == "__main__":
    seed_knowledge()